class StructureValidator:
    """Validate that created structure matches Arborescence_V7.txt"""
    
    def __init__(self, target_dir: Path, arborescence_path: Path):
        self.target_dir = target_dir.resolve()
        self.arborescence_path = arborescence_path
        
    def validate(self):
        """Validate structure conformance"""
        print("\n" + "=" * 70)
        print("STRUCTURE VALIDATION")
        print("=" * 70)
        
        # Parse arborescence
        parser = ArborescenceParser(self.arborescence_path)
        expected_structure = parser.load()
        
        # Get actual structure
        actual_files = []
        for root, dirs, files in os.walk(self.target_dir):
            for f in files:
                if not f.startswith('.') and not f.startswith('__'):
                    actual_files.append(Path(root).relative_to(self.target_dir) / f)
            for d in dirs:
                if not d.startswith('.'):
                    actual_files.append(Path(root).relative_to(self.target_dir) / d)
        
        actual_files = sorted([str(f).replace('\\', '/') for f in actual_files])
        expected_files = sorted([str(item['path']).replace('\\', '/') for item in expected_structure if not item['is_dir']])
        expected_dirs = sorted([str(item['path']).replace('\\', '/') for item in expected_structure if item['is_dir']])
        
        print(f"Expected files: {len(expected_files)}")
        print(f"Actual files: {len(actual_files)}")
        
        # Calculate conformance
        total_expected = len(expected_structure)
        total_actual = len(actual_files)
        conformance = (total_actual / total_expected * 100) if total_expected > 0 else 0
        
        print(f"\nConformance: {conformance:.1f}%")
        
        # Detailed comparison
        expected_set = set(expected_files)
        actual_set = set(actual_files)
        
        missing = expected_set - actual_set
        extra = actual_set - expected_set
        
        if missing:
            print(f"\n❌ Missing files ({len(missing)}):")
            for f in sorted(missing)[:10]:
                print(f"  - {f}")
            if len(missing) > 10:
                print(f"  ... and {len(missing) - 10} more")
        
        if extra:
            print(f"\n⚠️  Extra files ({len(extra)}):")
            for f in sorted(extra)[:10]:
                print(f"  - {f}")
            if len(extra) > 10:
                print(f"  ... and {len(extra) - 10} more")
        
        if not missing and not extra:
            print("\n✅ PERFECT CONFORMANCE - All files match!")
        
        return {
            'conformance': conformance,
            'missing': sorted(missing),
            'extra': sorted(extra),
            'is_conform': len(missing) == 0 and len(extra) == 0
        }


