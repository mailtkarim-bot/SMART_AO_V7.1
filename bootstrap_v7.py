class ArborescenceParser:
    """Parse Arborescence_V7.txt and extract file structure"""
    
    def __init__(self, arborescence_path: Path):
        self.arborescence_path = arborescence_path
        self.lines = []
        self.structure = []
        self.current_path = []
        self.current_indent = 0
        
    def load(self):
        """Load and parse the arborescence file"""
        if not self.arborescence_path.exists():
            raise FileNotFoundError(f"Arborescence file not found: {self.arborescence_path}")
        
        with open(self.arborescence_path, 'r', encoding='utf-8') as f:
            self.lines = f.readlines()
        
        self._parse_structure()
        return self.structure
    
    def _parse_structure(self):
        """Parse the tree structure from lines"""
        in_structure = False
        
        for line in self.lines:
            line = line.rstrip()
            
            # Skip comments and headers
            if line.startswith('#') or line.startswith('>') or not line.strip():
                continue
            
            # Check if we're in the structure section
            if 'SMART_AO/' in line:
                in_structure = True
            
            if in_structure:
                self._parse_line(line)
    
    def _parse_line(self, line: str):
        """Parse a single line of the tree structure with Unicode tree characters"""
        # Skip empty lines
        if not line.strip():
            return
        
        # Calculate indent level by counting "│   " patterns (each level adds "│   " at the start)
        # For level 0: "SMART_AO/" (no prefix)
        # For level 1: "├── " or "└── " (no "│   " prefix, but has tree connector)
        # For level 2: "│   ├── " or "│   └── " (one "│   " prefix)
        # For level 3: "│   │   ├── " (two "│   " prefixes)
        
        stripped = line.rstrip()
        indent_level = 0
        
        # Count the number of "│   " at the beginning
        while stripped.startswith('│   '):
            indent_level += 1
            stripped = stripped[4:]  # Remove "│   " (│ + 3 spaces = 4 chars)
        
        # Now check for tree connectors - these add +1 to the indent level
        # First, strip leading spaces and see if we have tree connectors
        temp_stripped = stripped.lstrip()
        
        if temp_stripped.startswith('├── '):
            # Count spaces before the connector (4 spaces per level)
            space_count = len(stripped) - len(temp_stripped)
            indent_level += space_count // 4
            name_part = temp_stripped[4:].split('  #')[0].strip()
            indent_level += 1  # Tree connectors are at indent_level + 1
            is_dir = name_part.endswith('/')
            if is_dir:
                name = name_part[:-1]
            else:
                name = name_part
        elif temp_stripped.startswith('└── '):
            space_count = len(stripped) - len(temp_stripped)
            indent_level += space_count // 4
            name_part = temp_stripped[4:].split('  #')[0].strip()
            indent_level += 1  # Tree connectors are at indent_level + 1
            is_dir = name_part.endswith('/')
            if is_dir:
                name = name_part[:-1]
            else:
                name = name_part
        elif stripped.startswith('│'):
            # This is a vertical line continuation without item, skip it
            return
        elif temp_stripped.startswith('│'):
            # This is a vertical line continuation without item, skip it
            return
        else:
            # This is the root level (e.g., "SMART_AO/")
            name = stripped.split('  #')[0].strip()
            is_dir = name.endswith('/')
            if is_dir:
                name = name[:-1]
            # Root level, reset and set current_path
            self.current_path = [name]
            indent_level = 0
        
        if not name:
            return
        
        # Update current path based on indent level
        while len(self.current_path) > indent_level:
            self.current_path.pop()
        
        # Add to structure
        full_path = Path(*self.current_path, name) if self.current_path else Path(name)
        
        # Re-check if it's a directory by looking at the original stripped content
        if not is_dir:
            # Check if name ends with / (some directories might not have been caught)
            if name.endswith('/'):
                is_dir = True
                name = name.rstrip('/')
        
        self.structure.append({
            'name': name,
            'path': full_path,
            'is_dir': is_dir,
            'indent': indent_level,
            'line': line
        })
        
        # Update current path for next items
        if is_dir:
            self.current_path.append(name)


