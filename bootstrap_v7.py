class BootstrapExecutor:
    """Execute the bootstrap process"""
    
    def __init__(self, target_dir: Path, dry_run: bool = False, force: bool = False):
        self.target_dir = target_dir.resolve()
        self.dry_run = dry_run
        self.force = force
        self.created_dirs = []
        self.created_files = []
        self.skipped_files = []
        self.errors = []
        
    def execute(self, structure: List[Dict]):
        """Execute bootstrap based on parsed structure"""
        print("=" * 70)
        print("SMART_AO V7 - Bootstrap Execution")
        print("=" * 70)
        print(f"Target directory: {self.target_dir}")
        print(f"Files to process: {len(structure)}")
        print(f"Mode: {'DRY RUN (simulation)' if self.dry_run else 'REAL EXECUTION'}")
        print("-" * 70)
        
        # Create target directory if it doesn't exist
        if not self.target_dir.exists():
            if not self.dry_run:
                self.target_dir.mkdir(parents=True, exist_ok=True)
                print(f"✅ Created target directory: {self.target_dir}")
            self.created_dirs.append(str(self.target_dir))
        
        # Process each item in structure
        for item in structure:
            self._process_item(item)
        
        # Print summary
        self._print_summary()
        
        return {
            'created_dirs': self.created_dirs,
            'created_files': self.created_files,
            'skipped_files': self.skipped_files,
            'errors': self.errors
        }
    
    def _process_item(self, item: Dict):
        """Process a single structure item"""
        target_path = self.target_dir / item['path']
        
        if item['is_dir']:
            self._create_directory(target_path, item)
        else:
            self._create_file(target_path, item)
    
    def _create_directory(self, path: Path, item: Dict):
        """Create a directory"""
        if path.exists():
            # Directory already exists
            return
        
        if self.dry_run:
            print(f"[DRY RUN] Would create directory: {path}")
            self.created_dirs.append(str(path))
            return
        
        try:
            path.mkdir(parents=True, exist_ok=True)
            print(f"📁 Created directory: {path}")
            self.created_dirs.append(str(path))
        except Exception as e:
            self.errors.append(f"Failed to create directory {path}: {e}")
            print(f"❌ Error creating directory {path}: {e}")
    
    def _create_file(self, path: Path, item: Dict):
        """Create a file with appropriate template"""
        if path.exists() and not self.force:
            # File already exists, skip
            print(f"⏭️  Skipped (exists): {path}")
            self.skipped_files.append(str(path))
            return
        
        # Get parent directory
        parent_dir = path.parent
        
        # Create parent directory if it doesn't exist
        if not parent_dir.exists():
            if not self.dry_run:
                parent_dir.mkdir(parents=True, exist_ok=True)
        
        # Determine file extension
        ext = path.suffix.lower().lstrip('.')
        if not ext and '.' in path.name:
            # Handle files with multiple dots (e.g., .env.example)
            ext = path.name.split('.')[-1]
        
        # Check for special cases
        file_name = path.name
        
        # Get template
        template_key = ext if ext else "default"
        template = TEMPLATES.get(template_key, TEMPLATES["default"])
        
        # Check for special templates
        special_key = str(path.relative_to(self.target_dir)).replace('/', '_').replace('.', '_')
        special_template = SPECIAL_TEMPLATES.get(str(path), None)
        if special_template:
            content = special_template
        else:
            # Customize template with file name
            content = template.format(file_name=file_name)
        
        if self.dry_run:
            print(f"[DRY RUN] Would create file: {path}")
            self.created_files.append(str(path))
            return
        
        try:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(content)
            print(f"📄 Created file: {path}")
            self.created_files.append(str(path))
        except Exception as e:
            self.errors.append(f"Failed to create file {path}: {e}")
            print(f"❌ Error creating file {path}: {e}")
    
    def _print_summary(self):
        """Print execution summary"""
        print("\n" + "=" * 70)
        print("SUMMARY")
        print("=" * 70)
        print(f"Directories created: {len(self.created_dirs)}")
        print(f"Files created: {len(self.created_files)}")
        print(f"Files skipped: {len(self.skipped_files)}")
        print(f"Errors: {len(self.errors)}")
        
        if self.errors:
            print("\n❌ ERRORS:")
            for error in self.errors:
                print(f"  - {error}")
        
        print("=" * 70)


